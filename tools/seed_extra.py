    for kind, rows in (("CASTLE", CASTLES), ("VILLAGE", VILLAGES), ("SANCTUARY", SANCTUARIES), ("ALTAR", ALTARS)):
        for i, (name, lat, lon) in enumerate(rows):
            sid = f"cur:{kind}:{i}:{name}"
            cur.execute(
                "INSERT OR REPLACE INTO sites VALUES (?,?,?,?,?,?,?,?,?)",
                (sid, name, kind, lat, lon, None, None, None, None),
            )
            n += 1
    conn.commit()
    print("inserted", n, dict(cur.execute("SELECT kind, COUNT(*) FROM sites GROUP BY kind")))
    conn.close()


